/**
 * Parameters of a UPI payment request. Each field maps to one query
 * parameter of the `upi://pay` URL (shown in brackets).
 *
 * Check the current NPCI UPI Linking Specifications for the exact rules your
 * use case must follow. This library only applies the shape checks and the
 * conservative defaults described on `validateUpiParams`.
 */
export interface UpiPaymentParams {
  /** Payee virtual payment address, for example `shop@okbank` (`pa`). */
  payeeVpa: string;
  /** Payee name shown in the UPI app (`pn`). */
  payeeName: string;
  /**
   * Amount in rupees, greater than zero with at most two decimals (`am`).
   * Pass a decimal string such as `'149.50'` to avoid floating point surprises.
   * A number is converted with `String(value)`, so `0.1 + 0.2` is rejected
   * instead of being rounded. The URL always carries exactly two decimals.
   */
  amount: string | number;
  /** Currency (`cu`). Only `'INR'` is accepted and it is the default. */
  currency?: UpiCurrency;
  /** Your reference for this order or payment (`tr`). */
  transactionRef: string;
  /** Short description shown to the payer (`tn`). */
  note: string;
  /** Merchant category code, four digits (`mc`). Optional. */
  merchantCode?: string;
  /** Transaction id generated by your PSP, if it gives you one (`tid`). Optional. */
  transactionId?: string;
  /** A link with details about the order (`url`). Optional. */
  url?: string;
}

export type UpiCurrency = 'INR';

export type UpiParamField = keyof UpiPaymentParams;

/**
 * - `REQUIRED`: a required value is missing or empty.
 * - `INVALID_TYPE`: the value is not a string (or a number, for `amount`).
 * - `INVALID_VPA`: `payeeVpa` does not look like `name@handle`.
 * - `INVALID_AMOUNT`: not a positive amount with at most two decimals.
 * - `INVALID_CURRENCY`: anything other than `'INR'`.
 * - `INVALID_MERCHANT_CODE`: `merchantCode` is not four digits.
 * - `INVALID_CHARACTERS`: the value cannot be URL-encoded (a lone UTF-16 surrogate).
 * - `TOO_LONG`: longer than the limit in `UpiLimits`.
 */
export type UpiProblemCode =
  | 'REQUIRED'
  | 'INVALID_TYPE'
  | 'INVALID_VPA'
  | 'INVALID_AMOUNT'
  | 'INVALID_CURRENCY'
  | 'INVALID_MERCHANT_CODE'
  | 'INVALID_CHARACTERS'
  | 'TOO_LONG';

export interface UpiProblem {
  code: UpiProblemCode;
  field: UpiParamField;
  message: string;
}

/**
 * Maximum lengths in characters (Unicode code points).
 *
 * The defaults in `DEFAULT_UPI_LIMITS` are conservative defaults chosen so
 * that common UPI apps accept the request. They are not quoted from the NPCI
 * specification. Check the current UPI Linking Specifications and your PSP's
 * documentation, and override them if you need to.
 */
export interface UpiLimits {
  payeeVpa: number;
  payeeName: number;
  transactionRef: number;
  note: number;
}

export interface UpiValidationOptions {
  /** Override some or all of `DEFAULT_UPI_LIMITS`. */
  limits?: Partial<UpiLimits>;
}

/**
 * Stable codes on `UpiError.code`:
 *
 * - `INVALID_PARAMS`: the parameters failed validation; see `problems`.
 * - `QR_TOO_LONG`: the text does not fit in the largest QR code at the
 *   chosen error correction level.
 */
export type UpiErrorCode = 'INVALID_PARAMS' | 'QR_TOO_LONG';

/**
 * What the browser is running on:
 *
 * - `android`: an Android phone or tablet.
 * - `ios`: an iPhone, iPod touch or iPad (including iPadOS in desktop mode).
 * - `desktop`: anything else.
 */
export type DeviceKind = 'android' | 'ios' | 'desktop';

/**
 * The answer of your server to "has this payment arrived?".
 *
 * - `paid`: your server has confirmed the money arrived. Final.
 * - `failed`: your server knows the payment failed. Final.
 * - `pending`: not known yet; ask again later.
 */
export type PaymentCheckResult = 'paid' | 'pending' | 'failed';

/**
 * - `idle`: not started. The mobile view stays here until a pay link is tapped.
 * - `waiting`: asking your server for the result.
 * - `paid`, `failed`, `expired`: final. Nothing is polled any more.
 */
export type UpiPaymentStatus = 'idle' | 'waiting' | 'paid' | 'failed' | 'expired';

/** Passed to `confirmPayment` on every check. */
export interface ConfirmPaymentContext {
  /** 1 for the first check of a payment, then 2, 3, ... */
  attempt: number;
  /**
   * Aborted when the result is no longer wanted: the component unmounted, or
   * the payment was restarted or reset. Pass it to `fetch` to cancel the
   * request. Not set where `AbortController` does not exist.
   */
  signal?: AbortSignal;
}

/**
 * Asks your server whether the payment arrived. A rejection counts as
 * `pending`: the hook keeps asking with backoff and exposes the error as
 * `lastCheckError`.
 */
export type ConfirmPayment = (context: ConfirmPaymentContext) => Promise<PaymentCheckResult>;
